func TestSQLTextCannotFabricateDDLTargets(t *testing.T) {
	root := goProject(t)
	writeProjectFile(t, root, "services/reports/schema.sql", `
SELECT 'CREATE TABLE public.reports (id INTEGER);';
SELECT 'x; CREATE TABLE public.reports (id INTEGER);';
-- CREATE TABLE public.reports (id INTEGER);
/* nested /* comment */ CREATE TABLE public.reports (id INTEGER); */
DO $body$ BEGIN; CREATE TABLE public.reports (id INTEGER); END $body$;
CREATE TABLE /*!50000 actual_table AS */ public.reports (id INTEGER);
CREATE TABLE /*M! actual_table AS */ public.reports (id INTEGER);
CREATE TABLE /*m! actual_table AS */ public.reports (id INTEGER);
CREATE TABLE "public.reports" (id INTEGER);
CREATE TABLE actual_table (id INTEGER);
`)
	db := newTestDB(t)
	result, err := Scan(db, root)
	if err != nil {
		t.Fatal(err)
	}
	if result.Stats.Tables != 1 {
		t.Fatalf("SQL text manufactured tables: %+v", result)
	}
	var count int
	if err := db.QueryRow(`SELECT COUNT(*) FROM relationships WHERE relationship_type = 'reads_table'`).Scan(&count); err != nil || count != 0 {
		t.Fatalf("query linked to fabricated DDL: %d %v", count, err)
	}
}
